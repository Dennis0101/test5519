    def save_results(self, results, filename='backtest_results.json'):
        """Save backtest results to file"""
        filepath = Path('logs') / filename
        filepath.parent.mkdir(exist_ok=True)
        
        # Convert numpy types for JSON serialization
        serializable = {}
        for key, value in results.items():
            if isinstance(value, (np.integer, np.floating)):
                serializable[key] = float(value)
            elif isinstance(value, list):
                serializable[key] = [float(x) if isinstance(x, (np.integer, np.floating)) else x for x in value]
            else:
                serializable[key] = value
        
        try:
            with open(filepath, 'w') as f:
                json.dump(serializable, f, indent=2)
            print(f"💾 Backtest results saved to {filepath}")
        except Exception as e:
            print(f"⚠️ Could not save backtest results: {e}")
